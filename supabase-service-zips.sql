-- ZIP codes inside the 100-mile local radius.
--
-- Locality decided the $150 out-of-town surcharge, and it was decided by matching
-- town names against the address with a wildcard. That is too loose to charge
-- money on: "Concord" is a town in NC, but also in California, New Hampshire and
-- Massachusetts, and any address containing the word matched. It also missed
-- every town not on the 38-row list, so a renter in Salisbury or Rock Hill - well
-- inside 100 miles - was charged $300 instead of $150.
--
-- 540 ZIP codes, every one within 100 miles of uptown Charlotte (35.2271,
-- -80.8431) by great-circle distance from its census centroid. NC 349, SC 181,
-- VA 6, TN 4.

